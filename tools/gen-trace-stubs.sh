#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-2.0-only
# Generate backends/xfs/shim/xfs_trace_names.h: one compiled-out stub per
# trace_xfs_*/trace_xlog_* tracepoint called by the given XFS sources
# (libxfs and the top-level .c files). Re-run after every
# kernel update (it only reads the sources). Usage:
#   tools/gen-trace-stubs.sh <fs/xfs dir> > backends/xfs/shim/xfs_trace_names.h
set -euo pipefail
src=${1:?usage: $0 <xfs source dir (with libxfs/)>}
echo "/* SPDX-License-Identifier: GPL-2.0-only */"
echo "/* Generated by tools/gen-trace-stubs.sh; do not edit. */"
echo "#ifndef WFS_XFS_TRACE_NAMES_H"
echo "#define WFS_XFS_TRACE_NAMES_H"
echo '#include "wfs_trace_base.h"'
{ grep -ohE '\btrace_(xfs|xlog)_[a-z0-9_]+' "$src"/libxfs/*.[ch] "$src"/*.c 2>/dev/null || true; } \
  | LC_ALL=C sort -u | grep -v '^trace_xfs_shim_test_event$' \
  | while read -r n; do printf '#define %s(...) WFS_TRACE(__VA_ARGS__)\n' "$n"; done
echo "#endif"
