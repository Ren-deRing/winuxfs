"""Summarize tools/xfs-shim-probe.sh compiler logs into a Markdown gap list.

Usage: python3 -I tools/xfs_shim_needs.py LOGDIR PRE(0|1)
"""
import re,glob,collections,os
import sys
D=sys.argv[1]
PRE=sys.argv[2] == '1'
impl=collections.defaultdict(set); undecl=collections.defaultdict(set); member=collections.defaultdict(set)
types=collections.defaultdict(set); other=collections.Counter()
for f in sorted(glob.glob(D+'/*.log')):
    n=os.path.basename(f)[:-4]
    cur_struct=None
    for l in open(f,errors='replace'):
        if ' error: ' not in l: continue
        m=re.search(r"implicit declaration of function ‘([^’]+)’",l)
        if m: impl[m.group(1)].add(n); continue
        m=re.search(r"‘([^’]+)’ undeclared",l)
        if m: undecl[m.group(1)].add(n); continue
        m=re.search(r"‘(struct [^’]+|[a-z_]+_t)’ has no member named ‘([^’]+)’",l)
        if m: member[m.group(1)].add(m.group(2)); continue
        m=re.search(r"(unknown type name|storage size of|incomplete type|invalid use of undefined type) ‘?([^’]*)’?",l)
        if m: types[m.group(2)].add(n); continue
        other[re.sub(r"‘[^’]*’","X",l.split(' error: ',1)[1].strip())]+=1
trace=sorted(k for k in impl if k.startswith('trace_'))
xfs=sorted(k for k in impl if k.startswith(('xfs_','xlog_')))
lin=sorted(k for k in impl if not k.startswith(('trace_','xfs_','xlog_')))
def files(s): return ', '.join(sorted(s))
print("# M3 shim needs (generated)\n")
print("Generated by `tools/xfs-shim-probe.sh" + (" --pre" if PRE else "") + "`: each M3 kernel file compiled with")
print("`-fsyntax-only` against the shim. Counts are first-order; fixing headers exposes more.\n")
if PRE:
    print("## Probe-only additions that the shim must make real\n")
    print("- `__releases(x)`, `__acquires(x)`, `__must_hold(x)`, `____cacheline_aligned_in_smp` (empty annotations)")
    print("- `<linux/iversion.h>` (`inode_inc_iversion` etc.), `xfs_qm.h` (quota off: shadow header)\n")
print(f"## Trace points: {len(trace)} missing `trace_*` (generate with tools/gen-trace-stubs.sh)\n")
print(', '.join(f"`{t}`" for t in trace)+"\n")
print(f"## Linux kernel APIs: {len(lin)}\n")
for k in lin: print(f"- `{k}` — {files(impl[k])}")
print(f"\n## XFS/xlog functions not declared through the shim: {len(xfs)}\n")
for k in xfs: print(f"- `{k}` — {files(impl[k])}")
print(f"\n## Undeclared identifiers: {len(undecl)}\n")
for k in sorted(undecl): print(f"- `{k}` — {files(undecl[k])}")
print(f"\n## Struct members missing from shim structs\n")
for k in sorted(member): print(f"- `{k}`: " + ', '.join(f"`{m}`" for m in sorted(member[k])))
print(f"\n## Types incomplete/unknown\n")
for k in sorted(types): print(f"- `{k}` — {files(types[k])}")
print("\n## Other errors (deduplicated, top 40)\n")
for k,c in other.most_common(40): print(f"- {c}× {k}")
